# 一般管理費等率の補正（別表第4：前払金支出割合 → 係数、別表第5：契約保証 → 加算値）
ADVANCE_FACTOR = (("0%から5%以下", 1.05), ("5%を超え15%以下", 1.04), ("15%を超え25%以下", 1.03), ("25%を超え35%以下", 1.01))
GUARANTEE_ADD = (("金銭", 0.04), ("役務", 0.09))


def key(work_type: str) -> str:
    """工種区分の表記ゆれをなくす（全角・空白・中点・かっこ）"""
    s = unicodedata.normalize("NFKC", work_type or "")
    s = re.sub(r"[\s・･()（）]", "", s).upper()
    return re.sub(r"^下水道(\d)工事$", r"下水道工事\1", s)


def params(fy: str, work_type: str, item: str):
    """(式, A, b, 下限, 上限) か None"""
    rows = STANDARD.get(fy) or STANDARD[max(STANDARD)]
    k = key(work_type)
    if item == "一般管理費等":
        return GENERAL if any(key(w) == k for w in WORK_TYPES) or k else None
    for w, it, f, a, b, lo, hi in rows:
        if it == item and key(w) == k:
            return f, a, b, lo, hi
    return None


def advance_factor(text: str, table=None) -> float:
    t = unicodedata.normalize("NFKC", text or "").replace(" ", "")
    if not t or "行わない" in t or "しない" in t:
        return 1.0
    for label, f in (table or ADVANCE_FACTOR):
        if unicodedata.normalize("NFKC", label) in t:
            return f
    return 1.0


def guarantee_add(text: str, table=None) -> float:
    t = unicodedata.normalize("NFKC", text or "")
    if not t or "しない" in t or "行わない" in t:
        return 0.0
    return next((v for k, v in (table or GUARANTEE_ADD) if k in t), 0.0)


